"""In-process PR-06 wiring: PM, Developer, QA, PR-01/06/09 contracts.

This is an explicitly supervised control-plane skeleton, not a worker runtime.
No model calls, process spawning, approval broker, network, or executor. A
PROCESS_SUCCEEDED report is never QA_VERIFIED. In-process principal tokens are
not an OS security boundary: never expose this API to untrusted workers.
"""
from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass

from subagentbridge.domain.contracts import Run, Task, TaskState, Role, Evidence
from subagentbridge.domain.engine import TaskAggregate, InvalidTransition
from subagentbridge.domain.registry import (
    IdentityRegistry, Principal, ReceiptIssuerRegistry,
)
from subagentbridge.planner.budget import BudgetLedger, validate_task_dag
from subagentbridge.qa.adjudication import QaEvidenceGate, EvidenceDecision


@dataclass(frozen=True, slots=True)
class DispatchPlan:
    task_id: str
    dispatch_id: str
    policy_revision: str
    tree_sha: str
    # This is NOT an authorization to launch an unconfined CLI.
    runtime_authorized: bool = False


class SupervisedCoordinator:
    """Deterministic task-state wiring, not a production composition root.

    The caller must provide a trusted in-process IdentityRegistry. This does
    not protect against a malicious same-user process or worker. Evidence
    issuer capabilities are **never** returned from this class.
    """

    def __init__(self, *, run: Run, tasks: Mapping[str, Task],
                 dependencies: Mapping[str, tuple[str, ...]],
                 identities: IdentityRegistry, receipts: ReceiptIssuerRegistry,
                 budget: BudgetLedger, qa_test_hashes: Mapping[str, str]):
        if not tasks or set(tasks) != set(dependencies):
            raise ValueError('run task and DAG identities must match')
        if any(t.task_id != key or t.run_id != run.run_id or
               t.policy_revision != run.policy_revision for key, t in tasks.items()):
            raise ValueError('task identity or policy revision mismatch')
        self.order = validate_task_dag(dependencies, {
            key: task.acceptance_criteria for key, task in tasks.items()})
        if not qa_test_hashes:
            raise ValueError('QA test hashes must be pinned before dispatch')
        self.run = run
        self.dependencies = {k: tuple(v) for k, v in dependencies.items()}
        self.identities = identities
        self.receipts = receipts
        self.budget = budget
        self._tasks = {k: TaskAggregate(t, identities, receipts) for k, t in tasks.items()}
        self._test_hashes = dict(qa_test_hashes)
        self._active_ids: dict[str, str] = {}
        self._fix_rounds: dict[str, int] = {k: 0 for k in tasks}

    def state(self, task_id: str) -> TaskState:
        return self._tasks[task_id].state

    def freeze(self, task_id: str, pm: Principal) -> None:
        self.identities.require(pm, Role.PM)
        self._tasks[task_id].freeze(pm)

    def begin(self, task_id: str, *, pm: Principal, idempotency_key: str,
              token_allowance: int, cost_microunits: int) -> DispatchPlan:
        self.identities.require(pm, Role.PM)
        if task_id not in self._tasks:
            raise KeyError('unknown task')
        agg = self._tasks[task_id]
        if agg.state is not TaskState.FROZEN:
            raise InvalidTransition('frozen task required for dispatch')
        if any(self._tasks[dep].state is not TaskState.VERIFIED for dep in self.dependencies[task_id]):
            raise InvalidTransition('dependencies must be QA VERIFIED, not PROCESS_SUCCEEDED')
        # Avoid a failed budget reservation after advancing the task state.
        # Dispatch ID is generated by PR-01 aggregate; reservation admission
        # failure must not leave a stranded new dispatch.
        if (type(token_allowance) is not int or type(cost_microunits) is not int
                or token_allowance < 0 or cost_microunits < 0):
            raise ValueError("nonnegative integer reservation ceilings required")
        if not idempotency_key:
            raise InvalidTransition('missing idempotency key')
        snap = self.budget.snapshot()
        if (snap['active'] >= self.budget.max_workers or token_allowance > snap['tokens_available']
            or cost_microunits > snap['cost_available']):
            from subagentbridge.planner.budget import BudgetExceeded
            raise BudgetExceeded('budget or concurrency ceiling exceeded')
        d = agg.dispatch(pm, idempotency_key=idempotency_key)
        try:
            self.budget.reserve(dispatch_id=d.dispatch_id, token_allowance=token_allowance,
                                cost_microunits=cost_microunits)
        except BaseException:
            agg.recover_unknown()  # cannot roll back consumed idempotency safely
            raise
        self._active_ids[task_id] = d.dispatch_id
        return DispatchPlan(task_id, d.dispatch_id, d.policy_revision, d.tree_sha)

    def report_process_succeeded(self, *, developer: Principal, task_id: str,
                                 dispatch_id: str, tree_sha: str) -> None:
        self.identities.require(developer, Role.DEVELOPER)
        self._tasks[task_id].process_succeeded(dispatch_id, tree_sha)

    def qa_review(self, *, qa: Principal, task_id: str, evidence: tuple[Evidence, ...],
                  covered_criteria: tuple[str, ...], actual_test_hashes: Mapping[str, str],
                  actual_tree_sha: str, clean: bool, fix_round: int = 0,
                  human_waiver: bool = False) -> EvidenceDecision:
        self.identities.require(qa, Role.QA)
        if task_id not in self._tasks:
            raise KeyError('unknown task')
        agg = self._tasks[task_id]
        if agg.state is not TaskState.PROCESS_SUCCEEDED or agg.active_dispatch is None:
            raise InvalidTransition('QA review requires PROCESS_SUCCEEDED')

        # Enforce fix-round cap: count is tracked internally per task and cannot be reset by caller
        current_round = max(self._fix_rounds.get(task_id, 0), fix_round if type(fix_round) is int and fix_round >= 0 else 0)
        if current_round >= 3:
            agg.block()
            if task_id in self._active_ids:
                dispatch_id = self._active_ids.pop(task_id)
                try:
                    self.budget.release(dispatch_id)
                except Exception:
                    pass
            return EvidenceDecision('BLOCKED', 'three fix rounds exhausted: human required')

        gate = QaEvidenceGate(self.receipts,
            frozen_criteria=agg.task.acceptance_criteria, qa_test_hashes=self._test_hashes)
        decision, verdict = gate.check(qa=qa, evidence=evidence,
            covered_criteria=covered_criteria, actual_test_hashes=actual_test_hashes,
            task_id=task_id, dispatch_id=agg.active_dispatch.dispatch_id,
            expected_tree=agg.task.tree_sha, actual_tree=actual_tree_sha,
            checkout_clean=clean, fix_round=current_round, human_waiver=human_waiver)

        if verdict is not None and decision.status == 'QA_VERIFIED':
            agg.qa_verified(qa, verdict)
            agg.mark_verified(qa)
            dispatch_id = self._active_ids.pop(task_id)
            # No refund from developer/LLM token claims. Budget remains charged.
            self.budget.release(dispatch_id)
        else:
            self._fix_rounds[task_id] = current_round + 1
            if self._fix_rounds[task_id] >= 3:
                agg.block()
                if task_id in self._active_ids:
                    dispatch_id = self._active_ids.pop(task_id)
                    try:
                        self.budget.release(dispatch_id)
                    except Exception:
                        pass
                return EvidenceDecision('BLOCKED', 'three fix rounds exhausted: human required')

        return decision

    def reconcile_recovery(self, task_id: str, *, pm: Principal, new_tree_sha: str | None = None) -> None:
        self.identities.require(pm, Role.PM)
        if task_id not in self._tasks:
            raise KeyError('unknown task')
        agg = self._tasks[task_id]
        if agg.state is not TaskState.RECOVERY_REQUIRED:
            raise InvalidTransition('reconcile_recovery requires RECOVERY_REQUIRED')
        if task_id in self._active_ids:
            dispatch_id = self._active_ids.pop(task_id)
            try:
                self.budget.release(dispatch_id)
            except Exception:
                pass
        agg.reconcile(pm, new_tree_sha=new_tree_sha)

    def update_tree(self, new_tree_sha: str) -> None:
        """Revoke all local success states, even dependent task verdicts.

        An active dispatch needs human recovery; never silently discard it or
        claim its OS process was killed. The old reservation stays charged.
        """
        if not new_tree_sha:
            raise ValueError('tree SHA is mandatory')
        for agg in self._tasks.values():
            if agg.task.tree_sha == new_tree_sha:
                continue
            if agg.state in (TaskState.DISPATCHED, TaskState.PROCESS_SUCCEEDED):
                agg.recover_unknown()
                # Keep existing task SHA until human reconciles the process.
                continue
            if agg.state is TaskState.RECOVERY_REQUIRED:
                # Sticky recovery state: cannot be cleared by repeated tree update before reconciliation
                continue
            if agg.state is TaskState.CREATED:
                task = agg.task
                agg.task = Task(task.task_id, task.run_id, task.acceptance_criteria,
                                new_tree_sha, task.policy_revision)
            else:
                agg.change_tree(new_tree_sha)

    def snapshot(self) -> dict:
        """Observability only. No credentials, approvals, or worker handles."""
        return {'run_id': self.run.run_id, 'autonomy': False,
                'tasks': {k: agg.state.value for k, agg in self._tasks.items()},
                'budget': self.budget.snapshot()}
